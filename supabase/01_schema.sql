-- ---------- Enquiries & visit requests ----------
create table if not exists public.enquiries (
  id            integer generated by default as identity primary key,
  customer_name text not null,
  phone         text not null,
  email         text not null default '',
  property_id   integer references public.properties(id) on delete set null,
  subject       text not null default '',
  source        text not null default 'contact' check (source in ('contact','list_property','property')),
  message       text not null default '',
  status        text not null default 'New' check (status in ('New','Contacted','Completed','Archived')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists enquiries_status_idx on public.enquiries (status, created_at desc);

create table if not exists public.visit_requests (
  id             integer generated by default as identity primary key,
  customer_name  text not null,
  phone          text not null,
  email          text not null default '',
  property_id    integer references public.properties(id) on delete set null,
  property_title text not null default '',
  preferred_date date not null,
  preferred_time text not null default '',
  visitors       integer not null default 1 check (visitors between 1 and 50),
  message        text not null default '',
  status         text not null default 'New' check (status in ('New','Confirmed','Completed','Cancelled')),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists visit_status_idx on public.visit_requests (status, created_at desc);

-- ---------- updated_at triggers ----------
do $$
declare t text;
begin
  foreach t in array array['properties','projects','services','team_members','site_content','settings','enquiries','visit_requests']
  loop
    execute format('drop trigger if exists %I_updated on public.%I', t, t);
    execute format('create trigger %I_updated before update on public.%I for each row execute function public.set_updated_at()', t, t);
  end loop;
end $$;

-- ---------- Row Level Security: ONLY admins can touch tables directly ----------
do $$
declare t text;
begin
  foreach t in array array['admin_profiles','properties','projects','services','team_members','site_content','settings','enquiries','visit_requests']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists admin_all on public.%I', t);
    execute format('create policy admin_all on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;
-- Visitors (anon) get NO direct table access; they use the safe functions below.
revoke all on all tables in schema public from anon;

-- ---------- Public data for the website (one safe call) ----------
create or replace function public.public_bootstrap() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'content',  coalesce((select jsonb_agg(jsonb_build_object('key',key,'value',value,'value_bn',value_bn)) from site_content), '[]'::jsonb),
    'settings', coalesce((select jsonb_agg(jsonb_build_object('key',key,'value',value)) from settings where key <> 'lead'), '[]'::jsonb),
    'services', coalesce((select jsonb_agg(to_jsonb(s) order by s.sort_order, s.id) from (
                   select id,title,title_bn,description,description_bn,image,icon,cta_label,cta_label_bn,cta_href,sort_order
                   from services where status='active') s), '[]'::jsonb),
    'projects', coalesce((select jsonb_agg(to_jsonb(p) order by p.sort_order, p.created_at desc) from (
                   select id,title,slug,location,description,images,status,project_type,sort_order,created_at
                   from projects where publish_status='published') p), '[]'::jsonb),
    'properties', coalesce((select jsonb_agg(to_jsonb(x) order by x.featured desc, x.created_at desc) from (
                   select id,title,slug,property_type,listing_type,location,address,price,discount_percent,area,bedrooms,bathrooms,
                          description,features,images,status,featured,is_demo,created_at
                   from properties where publish_status='published' limit 1000) x), '[]'::jsonb),
    'team',     coalesce((select jsonb_agg(to_jsonb(m) order by m.sort_order, m.id) from (
                   select id,name,name_bn,role,role_bn,photo,sort_order from team_members where status='active') m), '[]'::jsonb)
  );
$$;

-- ---------- Visitor forms (validated again here, because anyone can call these) ----------
create or replace function public.submit_enquiry(p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_name text := left(btrim(coalesce(p->>'customer_name','')), 100);
  v_phone text := left(btrim(coalesce(p->>'phone','')), 30);
  v_email text := left(btrim(coalesce(p->>'email','')), 254);
  v_msg text := left(btrim(coalesce(p->>'message','')), 2000);
  v_subject text := left(btrim(coalesce(p->>'subject','')), 200);
  v_source text := coalesce(nullif(p->>'source',''), 'contact');
  v_pid integer := nullif(p->>'property_id','')::integer;
  v_ptitle text;
begin
  if length(v_name) < 2 or length(v_msg) < 2 then raise exception 'invalid_input'; end if;
  if regexp_replace(v_phone, '[\s-]', '', 'g') !~ '^(\+?88)?01[3-9][0-9]{8}$' then raise exception 'invalid_phone'; end if;
  if v_email <> '' and v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'invalid_email'; end if;
  if v_source not in ('contact','list_property','property') then v_source := 'contact'; end if;
  if (select count(*) from enquiries where phone = v_phone and created_at > now() - interval '1 hour') >= 5
     or (select count(*) from enquiries where created_at > now() - interval '1 hour') >= 100 then
    raise exception 'too_many';
  end if;
  if v_pid is not null then
    select title into v_ptitle from properties where id = v_pid and publish_status = 'published';
    if v_ptitle is null then v_pid := null; end if;
  end if;
  insert into enquiries (customer_name, phone, email, property_id, subject, source, message)
  values (v_name, v_phone, v_email, v_pid, coalesce(nullif(v_subject,''), v_ptitle, ''), v_source, v_msg);
end $$;

create or replace function public.submit_visit(p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_name text := left(btrim(coalesce(p->>'customer_name','')), 100);
  v_phone text := left(btrim(coalesce(p->>'phone','')), 30);
  v_email text := left(btrim(coalesce(p->>'email','')), 254);
  v_msg text := left(btrim(coalesce(p->>'message','')), 2000);
  v_time text := left(btrim(coalesce(p->>'preferred_time','')), 60);
  v_title text := left(btrim(coalesce(p->>'property_title','')), 200);
  v_date date := (p->>'preferred_date')::date;
  v_vis integer := greatest(1, least(50, coalesce(nullif(p->>'visitors','')::integer, 1)));
  v_pid integer := nullif(p->>'property_id','')::integer;
  v_ptitle text;
begin
  if length(v_name) < 2 or v_time = '' or v_date is null then raise exception 'invalid_input'; end if;
  if regexp_replace(v_phone, '[\s-]', '', 'g') !~ '^(\+?88)?01[3-9][0-9]{8}$' then raise exception 'invalid_phone'; end if;
  if v_email <> '' and v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'invalid_email'; end if;
  if v_date < current_date - 1 then raise exception 'invalid_date'; end if;
  if (select count(*) from visit_requests where phone = v_phone and created_at > now() - interval '1 hour') >= 5
     or (select count(*) from visit_requests where created_at > now() - interval '1 hour') >= 100 then
    raise exception 'too_many';
  end if;
  if v_pid is not null then
    select title into v_ptitle from properties where id = v_pid and publish_status = 'published';
    if v_ptitle is null then v_pid := null; end if;
  end if;
  insert into visit_requests (customer_name, phone, email, property_id, property_title, preferred_date, preferred_time, visitors, message)
  values (v_name, v_phone, v_email, v_pid, coalesce(v_ptitle, v_title), v_date, v_time, v_vis, v_msg);
end $$;

-- ---------- Admin overview numbers ----------
create or replace function public.admin_stats() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'not_admin'; end if;
  return jsonb_build_object(
    'total_properties',     (select count(*) from properties),
    'available_properties', (select count(*) from properties where publish_status='published' and status='Available'),
    'featured_properties',  (select count(*) from properties where featured),
    'total_projects',       (select count(*) from projects),
    'total_services',       (select count(*) from services),
    'new_enquiries',        (select count(*) from enquiries where status='New'),
    'pending_visits',       (select count(*) from visit_requests where status in ('New','Confirmed')),
    'demo_properties',      (select count(*) from properties where is_demo));
end $$;

revoke all on function public.public_bootstrap(), public.submit_enquiry(jsonb), public.submit_visit(jsonb), public.admin_stats() from public;
grant execute on function public.public_bootstrap(), public.submit_enquiry(jsonb), public.submit_visit(jsonb) to anon, authenticated;
grant execute on function public.admin_stats() to authenticated;
grant execute on function public.is_admin() to authenticated;

-- ---------- Photo storage bucket (public read, admin-only write) ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('uploads', 'uploads', true, 5242880, array['image/jpeg','image/png','image/gif','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/gif','image/webp'];

drop policy if exists "uploads admin insert" on storage.objects;
drop policy if exists "uploads admin update" on storage.objects;
drop policy if exists "uploads admin delete" on storage.objects;
create policy "uploads admin insert" on storage.objects for insert to authenticated with check (bucket_id = 'uploads' and public.is_admin());
create policy "uploads admin update" on storage.objects for update to authenticated using (bucket_id = 'uploads' and public.is_admin());
create policy "uploads admin delete" on storage.objects for delete to authenticated using (bucket_id = 'uploads' and public.is_admin());
