create or replace function public.set_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at = now(); return new; end $$;

-- ---------- Admin profiles (login itself is handled by Supabase Auth) ----------
create table if not exists public.admin_profiles (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  name       text not null default 'Admin',
  role       text not null default 'admin' check (role in ('admin','editor')),
  created_at timestamptz not null default now()
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admin_profiles where user_id = auth.uid());
$$;

-- ---------- Properties ----------
create table if not exists public.properties (
  id               integer generated by default as identity primary key,
  title            text not null,
  slug             text not null unique,
  property_type    text not null,
  listing_type     text not null check (listing_type in ('buy','rent')),
  location         text not null,
  address          text not null default '',
  price            numeric(14,2) not null default 0 check (price >= 0),
  discount_percent numeric(5,2)  not null default 0 check (discount_percent >= 0 and discount_percent < 100),
  area             integer not null default 0 check (area >= 0),
  bedrooms         integer not null default 0 check (bedrooms >= 0),
  bathrooms        integer not null default 0 check (bathrooms >= 0),
  description      text not null default '',
  features         text[] not null default '{}',
  images           text[] not null default '{}',
  status           text not null default 'Available' check (status in ('Available','Sold','Rented')),
  publish_status   text not null default 'draft' check (publish_status in ('draft','published')),
  featured         boolean not null default false,
  is_demo          boolean not null default false,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists properties_publish_idx  on public.properties (publish_status, listing_type);
create index if not exists properties_featured_idx on public.properties (featured);

